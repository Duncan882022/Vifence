EVENT_REPEAT_MIN_SECONDS=900.0
EVENT_TEST_MODE=true
A03_BPTC_EVENT_LOGGING_ENABLED=true
EOF
echo "→ backend-ai/.env (VMS local, inference bật, auto-train thu mẫu tắt)"

echo ""
echo "✓ Local dev sẵn sàng."
echo "  1. SSH_KEY=~/.ssh/vifence_contabo ./scripts/pull-auto-train.sh  (parity weights)"
echo "  2. npm run start:local"
