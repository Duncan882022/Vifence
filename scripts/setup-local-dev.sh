AUTO_TRAIN_SCHEDULE_WINDOW_MINUTES=90
AUTO_TRAIN_CHECK_INTERVAL_SECONDS=120
AUTO_TRAIN_MIN_INTERVAL_SECONDS=39600
AUTO_TRAIN_MIN_NEW_SAMPLES_DELTA=10

VMS_MODE_ENABLED=true
VMS_CAMERA_SOURCES=A-03:${CAM03},A-04:${CAM04}
VMS_AI_FPS=6.0

DETECTION_FPS=6.0
STREAM_FPS=12.0

FIRE_MODEL_REPO=SalahALHaismawi/yolov26-fire-detection
FIRE_MODEL_FILE=best.pt
FIRE_CONF_THRESHOLD=0.62
FLAME_HEURISTIC_CONF_THRESHOLD=0.48

SMOKING_MODEL_REPO=Enos-123/smoking-detection
SMOKING_MODEL_FILE=best.pt
SMOKING_CONF_THRESHOLD=0.5

EVENT_COOLDOWN_SECONDS=900.0
